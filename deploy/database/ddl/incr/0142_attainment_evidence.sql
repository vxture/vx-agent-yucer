-- Verified first cooperation, including history before yucer. No backfill guesses.
BEGIN;
CREATE TABLE IF NOT EXISTS yucer_core.account_cooperation_history (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
  workspace_id UUID NOT NULL,
  account_id UUID NOT NULL,
  state VARCHAR(16) NOT NULL CHECK (state IN ('unknown','never','dated','before_year')),
  first_date DATE CHECK (first_date IS NULL OR (first_date >= DATE '1900-01-01' AND first_date <= recorded_at::date)),
  before_year SMALLINT,
  acquisition_owner_sub VARCHAR(128),
  acquisition_territory_id UUID,
  evidence VARCHAR(500) NOT NULL CHECK (length(trim(evidence)) > 0),
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  recorded_by VARCHAR(128) NOT NULL,
  request_key VARCHAR(128) NOT NULL,
  CHECK ((state = 'dated' AND first_date IS NOT NULL AND before_year IS NULL)
    OR (state = 'before_year' AND first_date IS NULL AND before_year IS NOT NULL AND before_year BETWEEN 1901 AND extract(year from recorded_at))
    OR (state IN ('unknown','never') AND first_date IS NULL AND before_year IS NULL)),
  CHECK (state = 'dated' OR (acquisition_owner_sub IS NULL AND acquisition_territory_id IS NULL))
);
-- Account ids are globally unique; composite trigger also checks workspace.
CREATE FUNCTION yucer_core.check_cooperation_account() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM yucer_core.account a
    WHERE a.id = NEW.account_id AND a.workspace_id = NEW.workspace_id AND a.deleted_at IS NULL) THEN
    RAISE EXCEPTION 'cooperation account unavailable' USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_cooperation_account BEFORE INSERT ON yucer_core.account_cooperation_history
FOR EACH ROW EXECUTE FUNCTION yucer_core.check_cooperation_account();
CREATE UNIQUE INDEX uidx_cooperation_request ON yucer_core.account_cooperation_history(workspace_id, request_key);
CREATE INDEX idx_cooperation_account ON yucer_core.account_cooperation_history(workspace_id, account_id, sequence);
GRANT SELECT, INSERT ON yucer_core.account_cooperation_history TO yucer_svc;
GRANT USAGE ON SEQUENCE yucer_core.account_cooperation_history_sequence_seq TO yucer_svc;
REVOKE UPDATE, DELETE ON yucer_core.account_cooperation_history FROM yucer_svc;
REVOKE ALL ON FUNCTION yucer_core.check_cooperation_account() FROM PUBLIC;
CREATE TABLE IF NOT EXISTS yucer_gtm.plan_action_result (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
  workspace_id UUID NOT NULL,
  revision_id UUID NOT NULL REFERENCES yucer_gtm.sales_plan_revision(id),
  action_key VARCHAR(128) NOT NULL,
  account_id UUID NOT NULL REFERENCES yucer_core.account(id),
  met BOOLEAN NOT NULL,
  evidence VARCHAR(500) NOT NULL CHECK(length(trim(evidence)) > 0),
  occurred_at DATE NOT NULL CHECK (occurred_at >= DATE '1900-01-01' AND occurred_at <= recorded_at::date),
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  recorded_by VARCHAR(128) NOT NULL,
  request_key VARCHAR(128) NOT NULL
);
CREATE FUNCTION yucer_gtm.check_plan_action_result() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM yucer_gtm.sales_plan_revision r,
    LATERAL jsonb_array_elements(r.content->'actions') a
    WHERE r.id=NEW.revision_id AND r.workspace_id=NEW.workspace_id AND r.state='sealed'
      AND a->>'key'=NEW.action_key AND a->>'accountId'=NEW.account_id::text)
    OR NOT EXISTS (SELECT 1 FROM yucer_core.account c WHERE c.id=NEW.account_id AND c.workspace_id=NEW.workspace_id AND c.deleted_at IS NULL) THEN
    RAISE EXCEPTION 'plan action unavailable' USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_plan_action_result BEFORE INSERT ON yucer_gtm.plan_action_result
FOR EACH ROW EXECUTE FUNCTION yucer_gtm.check_plan_action_result();
CREATE UNIQUE INDEX uidx_plan_action_result_request ON yucer_gtm.plan_action_result(workspace_id,request_key);
CREATE INDEX idx_plan_action_result ON yucer_gtm.plan_action_result(workspace_id,revision_id,action_key,sequence);
GRANT SELECT, INSERT ON yucer_gtm.plan_action_result TO yucer_svc;
GRANT USAGE ON SEQUENCE yucer_gtm.plan_action_result_sequence_seq TO yucer_svc;
REVOKE UPDATE, DELETE ON yucer_gtm.plan_action_result FROM yucer_svc;
REVOKE ALL ON FUNCTION yucer_gtm.check_plan_action_result() FROM PUBLIC;
COMMIT;
